import { defineStore } from 'pinia'

/**
 * Сколько последних разниц держим для оценки сдвига.
 *
 * Окно нужно, чтобы оценка пережила перевод часов: минимум по всей истории
 * после такого перевода остался бы неверным навсегда
 */
const SKEW_SAMPLES_LIMIT = 32

/**
 * Переводит серверные отметки времени в возраст события, не полагаясь
 * на точность локальных часов.
 *
 * Апи и лонгполл присылают время в своей системе координат, а всё остальное
 * в приложении считается по Date.now(). Сравнивать их напрямую нельзя: часы
 * пользователя ничем не обязаны совпадать с серверными, и ухода на минуту уже
 * хватает, чтобы сломать любую проверку «насколько это свежее» — причём молча
 * и в обе стороны.
 *
 * Оценкой сдвига служит наименьшая из недавно наблюдённых разниц: задержка
 * доставки всегда неотрицательна, поэтому меньшая разница ближе к настоящему
 * сдвигу часов. События из старой пачки дают заведомо большую разницу
 * и оценку не портят
 */
export const useServerClockStore = defineStore('serverClock', {
  state: () => ({
    /** Разницы «локальное время минус серверное» по недавним событиям */
    samples: [] as number[]
  }),

  getters: {
    /** Пока разниц не наблюдали, считаем сдвиг нулевым */
    skew(state): number {
      return state.samples.length > 0 ? Math.min(...state.samples) : 0
    }
  },

  actions: {
    /** Запоминает разницу по отметке времени пришедшего события */
    observe(serverTimeMs: number) {
      if (!Number.isFinite(serverTimeMs)) {
        return
      }

      this.samples.push(Date.now() - serverTimeMs)

      if (this.samples.length > SKEW_SAMPLES_LIMIT) {
        this.samples.shift()
      }
    },

    /** Возраст события в миллисекундах */
    age(serverTimeMs: number): number {
      return Date.now() - serverTimeMs - this.skew
    }
  }
})
